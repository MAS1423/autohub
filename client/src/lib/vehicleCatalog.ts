export function formatSAR(value: number | string | undefined | null): string {
  const number = Number(value);
  if (!Number.isFinite(number) || number <= 0) return 'غير محدد';
  return `${new Intl.NumberFormat('ar-SA').format(number)} ر.س`;
}
